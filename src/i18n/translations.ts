export function getBilingualText(
  lang: Language,
  enValue?: string | null,
  hiValue?: string | null
): { text: string; isFallbackLanguage: boolean } {
  const en = (enValue || '').trim();
  const hi = (hiValue || '').trim();
  if (lang === 'hi') {
    if (hi) return { text: hi, isFallbackLanguage: false };
    return { text: en, isFallbackLanguage: Boolean(en) };
  }
  if (en) return { text: en, isFallbackLanguage: false };
  return { text: hi, isFallbackLanguage: Boolean(hi) };
}

export function formatDateBilingual(iso: string | null | undefined, lang: Language): string {
  if (!iso) return '';
  const d = new Date(iso);
  if (Number.isNaN(d.getTime())) return '';
  return d.toLocaleDateString(lang === 'hi' ? 'hi-IN' : 'en-US', {
    year: 'numeric',
    month: 'short',
    day: 'numeric',
  });
}
